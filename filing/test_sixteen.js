// Sixteen tags on two chains (the full depth-4 ledger tree), at WITNESS level:
// the Groth16 setup of Boundary(16, 64) needs a 2^21 powers-of-tau file, so
// no boundary proof is made here (filing/bench_boundary16.sh does that once
// the file is available).
//  1 every step witness of the 64-step filing is computed with the real step
//    circuit wasm and equals the JS reference
//  2 the Boundary(16, 64) witness is computed with its real wasm (which
//    asserts every constraint) and its public signals equal the reference;
//    the witness file is written for `snarkjs wtns check` against the R1CS
//  3 negative: one of the 16 tags is dropped (none of its records is folded)
//    -> the steps are valid, the Boundary(16, 64) witness is REJECTED
//  --fold : also run the real fold of the 64 steps (IVC proof verified)
// Prereq: bash filing/bench_boundary16.sh compile
// Usage: node test_sixteen.js [--fold]
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");
const core = require("./lib/core");
const sc = require("./scenarios");
const { foldInputJson, boundaryPublic, toStr } = require("./lib/filing");
const { loadCalculator, stepWitness, shortErr } = require("./lib/wtns");

const BUILD = path.join(__dirname, "build");
const DIR = path.join(BUILD, "runs", "sixteen-tags");
const EXE = process.platform === "win32" ? ".exe" : "";
const FOLD_BIN = process.env.FILING_FOLD ||
  path.join(__dirname, "..", "folding", "sonobe", "target", "release", "examples", "filing_fold" + EXE);

let failures = 0;
const report = (ok, label) => { if (!ok) failures++; console.log(`  ${ok ? "ok  " : "FAIL"} ${label}`); };

async function main() {
  await core.init();
  fs.mkdirSync(DIR, { recursive: true });
  const wcStep = await loadCalculator("c_fstep");
  const wcB = await loadCalculator("c_boundary16");

  console.log("== 1 sixteen tags, two chains: step witnesses");
  const s = await sc.sixteenTags();
  const { f, check } = s.filings[0];
  check();
  const c = f.counts;
  let z = f.z0;
  for (let k = 0; k < f.steps.length; k++) {
    const w = await stepWitness(wcStep, z, f.steps[k]);
    if (w[1] !== f.digests[k]) throw new Error(`step ${k} digest differs from the reference`);
    z = w[1];
  }
  report(z === f.zn, `steps ${c.steps} = ${c.records} record + ${c.pslEntries} PSL entry + ${c.stillOpen} still open + ${c.padding} padding: every step witness equals the reference`);
  console.log(`       D = (${f.D.proceeds}, ${f.D.cost}, ${f.D.income}); end counters ${JSON.stringify(toStr(f.closingState.counters))}`);
  fs.writeFileSync(path.join(DIR, "fold_input.json"), JSON.stringify(foldInputJson(f)));
  fs.writeFileSync(path.join(DIR, "boundary_input.json"), JSON.stringify(toStr(f.boundary)));

  console.log("== 2 Boundary(16, 64) witness");
  const t0 = Date.now();
  const wtns = await wcB.calculateWTNSBin(toStr(f.boundary), 0);
  const wb = await wcB.calculateWitness(toStr(f.boundary), 0);
  const pub = boundaryPublic(f.boundary, 16);
  let pubOk = pub.length === 37;
  for (let k = 0; k < pub.length; k++) if (wb[1 + k].toString() !== pub[k]) pubOk = false;
  report(true, `witness generated by the circuit's wasm with all assertions on: ${wb.length} wires (${Date.now() - t0} ms for two runs)`);
  report(pubOk, `its ${pub.length} public signals (z0, zn, 16 tags, chain data, roots, y, D, C_prev, C_y, closing) equal the reference`);
  fs.writeFileSync(path.join(DIR, "boundary16.wtns"), wtns);
  fs.writeFileSync(path.join(DIR, "boundary16_public.json"), JSON.stringify(pub));
  console.log(`       witness file written: ${path.join(DIR, "boundary16.wtns")}`);

  console.log("== 3 negative: tag 5 dropped (none of its records folded), authority still demands all 16");
  const bad = await sc.sixteenTags({ strict: false, noPad: true,
    hooks: { events: (ev) => ev.filter((e) => !(e.type === "rec" && e.r.slot === 5)) } });
  const fb = bad.filings[0].f;
  let stepsOk = true;
  z = fb.z0;
  for (let k = 0; k < fb.steps.length; k++) {
    try { const w = await stepWitness(wcStep, z, fb.steps[k]); z = w[1]; } catch (e) { stepsOk = false; break; }
  }
  report(stepsOk, `all ${fb.steps.length} steps of the dishonest sequence are valid (the fold alone does not catch it)`);
  let why = null;
  try { await wcB.calculateWitness(toStr(fb.boundary), 0); } catch (e) { why = shortErr(e, "b16"); }
  report(why !== null, `Boundary(16, 64) witness: ${why ? "REJECTED at " + why : "ACCEPTED"}`);

  // --forced <zkey> <vkey>: with the Groth16 key of Boundary(16, 64) (needs the
  // 2^21 powers-of-tau file, see bench_boundary16.sh): a proof forced from the
  // non-satisfying witness of the dropped-tag input must not verify
  const fi = process.argv.indexOf("--forced");
  if (fi >= 0) {
    console.log("== 3b forced Groth16 proof of the dropped-tag input");
    const snarkjs = require("snarkjs");
    const zkey = process.argv[fi + 1];
    const vkey = JSON.parse(fs.readFileSync(process.argv[fi + 2], "utf8"));
    const wcF = await loadCalculator("c_boundary16", { force: true });
    wcF.resetFailed();
    const badWtns = await wcF.calculateWTNSBin(toStr(fb.boundary), 0);
    const ignored = wcF.failedAsserts;
    const t1 = Date.now();
    const { proof, publicSignals } = await snarkjs.groth16.prove(zkey, badWtns);
    const okv = await snarkjs.groth16.verify(vkey, publicSignals, proof);
    report(okv === false, `forced proof (${ignored} failed assertion(s) ignored, prove ${Date.now() - t1} ms): verify -> ${okv}`);
  }

  if (process.argv.includes("--fold")) {
    console.log("== 4 real fold of the 64 steps (Nova + CycleFold)");
    const r = spawnSync(FOLD_BIN, [path.join(DIR, "fold_input.json"), "--r1cs", path.join(BUILD, "c_fstep.r1cs"),
      "--wasm", path.join(BUILD, "c_fstep_js", "c_fstep.wasm"), "--out", path.join(DIR, "fold_output.json")],
      { encoding: "utf8", maxBuffer: 1 << 26 });
    fs.writeFileSync(path.join(DIR, "fold.log"), (r.stdout || "") + (r.stderr || ""));
    for (const l of (r.stdout || "").split(/\r?\n/)) {
      if (/^(folded|IVC verify|steps =|z_n equals|peak)/.test(l)) console.log("       [fold] " + l);
    }
    const fo = r.status === 0 ? JSON.parse(fs.readFileSync(path.join(DIR, "fold_output.json"), "utf8")) : null;
    report(r.status === 0 && fo.ivc_verified && fo.z0 === pub[0] && fo.zn === pub[1],
      "IVC proof verifies; fold z_0, z_n equal the public z0, zn of the Boundary(16, 64) witness");
  }
  console.log(failures === 0 ? "sixteen tags: ALL OK" : `sixteen tags: ${failures} FAILED`);
  process.exitCode = failures === 0 ? 0 : 1;
  // snarkjs keeps its curve workers alive; end them so the process can exit
  if (globalThis.curve_bn128) await globalThis.curve_bn128.terminate();
}
main().catch((e) => { console.error("FAILED:", e.message || e); process.exitCode = 1; });
